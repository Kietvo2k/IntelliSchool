export function defaultBlocksForMajor(majorCode: string, group?: string): readonly string[] {
  const code = majorCode.toUpperCase();
  if (code.startsWith('748') || code.startsWith('746') || code === 'CS' || code.includes('CNTT')) return ['A00', 'A01', 'X06'];
  if (code.startsWith('772') || code === 'MED') return ['B00', 'B08'];
  if (code.startsWith('738') || code.includes('LUAT') || code.includes('LAW')) return ['C00', 'D01', 'X70'];
  if (code.startsWith('734') || code.startsWith('731')) return ['A00', 'A01', 'D01', 'D07'];
  if (code.startsWith('721') || code.startsWith('722') || code.startsWith('732') || code.startsWith('714')) return ['C00', 'D01', 'D14'];
  if (code.startsWith('758') || code.startsWith('752')) return ['A00', 'A01', 'C01'];
  if (group === 'khtn') return ['A00', 'A01', 'B00'];
  if (group === 'khxh') return ['C00', 'D01', 'C03'];
  return ['A00', 'A01', 'D01', 'C00'];
}

